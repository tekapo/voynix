import React, { useEffect, useState } from 'react';
import { getVersion } from '@tauri-apps/api/app';
import { openUrl } from '@tauri-apps/plugin-opener';
import { useTranslation } from 'react-i18next';

export interface AboutTabProps {
    /** Whole-library totals (unfiltered). */
    libraryStats?: { tracks: number; artists: number; albums: number };
    onClose: () => void;
    /** Reopens the first-launch welcome guide. */
    onShowWelcome?: () => void;
    /** From useAboutInfo(). */
    version: string;
    licenses: string | null;
    toggleLicenses: () => void;
}
/**
 * Version + on-demand third-party license text for the About tab. Called from
 * SettingsModal (not AboutTab) so the values survive switching tabs, exactly
 * as when this state lived inline in the modal.
 */
export function useAboutInfo() {
    const { t } = useTranslation();
    // Shown in the About section — read from the bundle so it never drifts from
    // the app's actual version.
    const [version, setVersion] = useState('');
    useEffect(() => {
        getVersion().then(setVersion).catch(() => {});
    }, []);

    // Third-party license notices (public/licenses.txt, generated by
    // scripts/generate-licenses.mjs) — fetched on demand so the ~1 MB text
    // isn't part of the JS bundle.
    const [licenses, setLicenses] = useState<string | null>(null);
    const toggleLicenses = () => {
        if (licenses !== null) {
            setLicenses(null);
            return;
        }
        fetch('/licenses.txt')
            .then(res => (res.ok ? res.text() : Promise.reject(new Error(String(res.status)))))
            .then(setLicenses)
            .catch(() => setLicenses(t('settings.licensesLoadFailed')));
    };
    return { version, licenses, toggleLicenses };
}


export const AboutTab: React.FC<AboutTabProps> = ({
    libraryStats,
    onClose,
    onShowWelcome,
    version,
    licenses,
    toggleLicenses,
}) => {
    const { t } = useTranslation();
    return (
        <>
            <div className="settings-section">
                <p><strong>{t('settings.appName')}</strong>{version && t('settings.versionLabel', { version })}</p>
                <p className="settings-hint">{t('settings.aboutTagline')}</p>
                {libraryStats && (
                    <p className="settings-hint" data-testid="library-stats">
                        {t('settings.libraryStats', {
                            tracks: t('settings.libraryTracks', { count: libraryStats.tracks }),
                            artists: t('settings.libraryArtists', { count: libraryStats.artists }),
                            albums: t('settings.libraryAlbums', { count: libraryStats.albums }),
                        })}
                    </p>
                )}
                <div className="settings-about-actions">
                    {onShowWelcome && (
                        <button type="button" className="modal-btn secondary" onClick={() => { onClose(); onShowWelcome(); }}>
                            {t('settings.showWelcome')}
                        </button>
                    )}
                    <button type="button" className="modal-btn secondary" onClick={() => { openUrl(t('settings.websiteUrl')).catch(() => {}); }}>
                        {t('settings.userManual')}
                    </button>
                    <button type="button" className="modal-btn secondary" onClick={toggleLicenses}>
                        {t('settings.openSourceLicenses')}
                    </button>
                    <button type="button" className="modal-btn secondary" onClick={() => { openUrl(t('settings.supportUrl')).catch(() => {}); }}>
                        {t('settings.supportOnKofi')}
                    </button>
                </div>
                {licenses !== null && (
                    <pre className="settings-licenses" tabIndex={0}>{licenses}</pre>
                )}
            </div>
        </>
    );
};
